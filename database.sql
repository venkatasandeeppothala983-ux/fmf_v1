-- Find My Faculty / College Portal database schema and source-derived demonstration data.
-- Target: MySQL 8.0+. Import into a NEW/empty schema. No passwords, login accounts, or personal contact details are seeded.
-- Includes five user-approved public student directory records (names/IDs) in ADND / III Year / class-05 (S3); no individual logins.
-- The supplied verified schedules are represented as entered; NULL rooms/departments remain unknown.
CREATE DATABASE IF NOT EXISTS findmyfaculty CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE findmyfaculty;
SET NAMES utf8mb4;
SET time_zone = '+05:30';

CREATE TABLE IF NOT EXISTS department (
  id BIGINT NOT NULL AUTO_INCREMENT, code VARCHAR(24) NOT NULL, name VARCHAR(140) NOT NULL,
  description VARCHAR(500), active BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id), UNIQUE KEY uk_department_code (code), UNIQUE KEY uk_department_name (name)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS class_section (
  id BIGINT NOT NULL AUTO_INCREMENT, source_key VARCHAR(40) NOT NULL, year_label VARCHAR(40) NOT NULL,
  semester_label VARCHAR(40) NOT NULL, section_label VARCHAR(60) NOT NULL, class_incharge VARCHAR(180),
  source_file VARCHAR(180), PRIMARY KEY (id), UNIQUE KEY uk_section_source (source_key)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS classroom (
  id BIGINT NOT NULL AUTO_INCREMENT, code VARCHAR(80) NOT NULL, building VARCHAR(120), capacity INT,
  active BOOLEAN NOT NULL DEFAULT TRUE, PRIMARY KEY (id), UNIQUE KEY uk_classroom_code (code)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS subject (
  id BIGINT NOT NULL AUTO_INCREMENT, code VARCHAR(40), name VARCHAR(240) NOT NULL,
  department_id BIGINT, active BOOLEAN NOT NULL DEFAULT TRUE, PRIMARY KEY (id),
  UNIQUE KEY uk_subject_code (code), UNIQUE KEY uk_subject_name (name), KEY idx_subject_department (department_id),
  CONSTRAINT fk_subject_department FOREIGN KEY (department_id) REFERENCES department(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS faculty (
  id BIGINT NOT NULL AUTO_INCREMENT, source_key VARCHAR(40) NOT NULL, name VARCHAR(160) NOT NULL,
  department_id BIGINT, department VARCHAR(140), active BOOLEAN DEFAULT TRUE, cabin VARCHAR(100), email VARCHAR(180),
  PRIMARY KEY (id), UNIQUE KEY uk_faculty_source_key (source_key),
  CONSTRAINT fk_faculty_department FOREIGN KEY (department_id) REFERENCES department(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS faculty_subject (
  faculty_id BIGINT NOT NULL, subject_id BIGINT NOT NULL, UNIQUE KEY uk_faculty_subject (faculty_id,subject_id),
  CONSTRAINT fk_fs_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE CASCADE,
  CONSTRAINT fk_fs_subject FOREIGN KEY (subject_id) REFERENCES subject(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS faculty_course (
  faculty_id BIGINT NOT NULL, course_name VARCHAR(240), KEY idx_faculty_course_faculty (faculty_id),
  CONSTRAINT fk_fc_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_account (
  id BIGINT NOT NULL AUTO_INCREMENT, username VARCHAR(80) NOT NULL, password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(16) NOT NULL, faculty_id BIGINT, section_id BIGINT, enabled BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id), UNIQUE KEY uk_user_username (username), UNIQUE KEY uk_user_faculty (faculty_id),
  KEY idx_user_section (section_id), CONSTRAINT fk_user_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE SET NULL,
  CONSTRAINT fk_user_section FOREIGN KEY (section_id) REFERENCES class_section(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS student_profile (
  id BIGINT NOT NULL AUTO_INCREMENT, user_account_id BIGINT, full_name VARCHAR(160), student_number VARCHAR(40) NOT NULL,
  department_id BIGINT, year_label VARCHAR(40), section_id BIGINT, phone VARCHAR(30), active BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), PRIMARY KEY (id), UNIQUE KEY uk_student_number (student_number),
  UNIQUE KEY uk_student_user (user_account_id), KEY idx_student_department_year (department_id,year_label),
  CONSTRAINT fk_student_user FOREIGN KEY (user_account_id) REFERENCES user_account(id) ON DELETE CASCADE,
  CONSTRAINT fk_student_department FOREIGN KEY (department_id) REFERENCES department(id) ON DELETE SET NULL,
  CONSTRAINT fk_student_section FOREIGN KEY (section_id) REFERENCES class_section(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS timetable_entry (
  id BIGINT NOT NULL AUTO_INCREMENT, faculty_id BIGINT NOT NULL, day_name VARCHAR(12) NOT NULL, period_number INT NOT NULL,
  start_time TIME NOT NULL, end_time TIME NOT NULL, subject_label VARCHAR(240) NOT NULL, subject_id BIGINT,
  room VARCHAR(100), classroom_id BIGINT, source_file VARCHAR(180), PRIMARY KEY (id),
  KEY idx_timetable_faculty_day (faculty_id,day_name), KEY idx_timetable_day_time (day_name,start_time),
  CONSTRAINT fk_timetable_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id) ON DELETE CASCADE,
  CONSTRAINT fk_timetable_subject FOREIGN KEY (subject_id) REFERENCES subject(id) ON DELETE SET NULL,
  CONSTRAINT fk_timetable_room FOREIGN KEY (classroom_id) REFERENCES classroom(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS class_course (
  id BIGINT NOT NULL AUTO_INCREMENT, section_id BIGINT NOT NULL, course_code VARCHAR(120), course_name VARCHAR(320),
  faculty_name VARCHAR(180), subject_id BIGINT, PRIMARY KEY (id), KEY idx_class_course_section (section_id),
  CONSTRAINT fk_course_section FOREIGN KEY (section_id) REFERENCES class_section(id) ON DELETE CASCADE,
  CONSTRAINT fk_course_subject FOREIGN KEY (subject_id) REFERENCES subject(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS class_timetable_entry (
  id BIGINT NOT NULL AUTO_INCREMENT, section_id BIGINT NOT NULL, day_name VARCHAR(12) NOT NULL, period_number INT NOT NULL,
  start_time TIME NOT NULL, end_time TIME NOT NULL, subject VARCHAR(240) NOT NULL, subject_id BIGINT, room VARCHAR(180),
  classroom_id BIGINT, source_text VARCHAR(400), PRIMARY KEY (id), KEY idx_class_entry_section_day (section_id,day_name),
  CONSTRAINT fk_class_entry_section FOREIGN KEY (section_id) REFERENCES class_section(id) ON DELETE CASCADE,
  CONSTRAINT fk_class_entry_subject FOREIGN KEY (subject_id) REFERENCES subject(id) ON DELETE SET NULL,
  CONSTRAINT fk_class_entry_room FOREIGN KEY (classroom_id) REFERENCES classroom(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS appointment_request (
  id BIGINT NOT NULL AUTO_INCREMENT, faculty_id BIGINT NOT NULL, student_id BIGINT NOT NULL, requested_start DATETIME(6) NOT NULL,
  suggested_start DATETIME(6), reason VARCHAR(500) NOT NULL, conflict_warning VARCHAR(240), state VARCHAR(16) NOT NULL,
  created_at DATETIME(6) NOT NULL, updated_at DATETIME(6), PRIMARY KEY (id),
  KEY idx_appointment_faculty (faculty_id), KEY idx_appointment_student (student_id),
  CONSTRAINT fk_appointment_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id),
  CONSTRAINT fk_appointment_student FOREIGN KEY (student_id) REFERENCES user_account(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS faculty_status_update (
  id BIGINT NOT NULL AUTO_INCREMENT, faculty_id BIGINT NOT NULL, status VARCHAR(24) NOT NULL, location VARCHAR(180), note VARCHAR(240),
  updated_at DATETIME(6) NOT NULL, expected_return DATETIME(6), updated_by_user_id BIGINT, PRIMARY KEY (id),
  KEY idx_status_faculty_updated (faculty_id,updated_at), CONSTRAINT fk_status_faculty FOREIGN KEY (faculty_id) REFERENCES faculty(id),
  CONSTRAINT fk_status_user FOREIGN KEY (updated_by_user_id) REFERENCES user_account(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS announcement (
  id BIGINT NOT NULL AUTO_INCREMENT, title VARCHAR(160) NOT NULL, body VARCHAR(4000) NOT NULL, audience VARCHAR(16) NOT NULL,
  published BOOLEAN NOT NULL DEFAULT TRUE, starts_at DATETIME(6), ends_at DATETIME(6), created_by_user_id BIGINT,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6), PRIMARY KEY (id),
  KEY idx_announcement_publish_window (published,starts_at,ends_at), KEY idx_announcement_audience (audience),
  CONSTRAINT fk_announcement_user FOREIGN KEY (created_by_user_id) REFERENCES user_account(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS portal_notification (
  id BIGINT NOT NULL AUTO_INCREMENT, user_account_id BIGINT NOT NULL, title VARCHAR(140) NOT NULL, message VARCHAR(1000) NOT NULL,
  target_path VARCHAR(240), created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), read_at DATETIME(6), PRIMARY KEY (id),
  KEY idx_notification_user_created (user_account_id,created_at),
  CONSTRAINT fk_notification_user FOREIGN KEY (user_account_id) REFERENCES user_account(id) ON DELETE CASCADE
) ENGINE=InnoDB;

